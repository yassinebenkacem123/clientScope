import assert from "node:assert/strict";
import { DEFAULT_CLIENTS } from "../src/components/dashboard/clients/clients-data";
import { getClientProjects } from "../src/components/dashboard/clients/client-projects-data";
import { deleteQuoteDraft, getClientQuotes, latestClientQuotes, prepareClientQuote, quoteDisplayStatus, quoteLineTotal, quoteStatistics, quoteTotal, saveQuoteDraft, validateQuoteDraft, type QuoteDraft } from "../src/components/dashboard/clients/client-quotes-data";
import { deleteClientNote, getClientNotes, pinClientNote, saveClientNote, validateNoteDraft, type NoteDraft } from "../src/components/dashboard/clients/client-notes-data";

const projectId = getClientProjects(DEFAULT_CLIENTS[0])[0].id;
const draft: QuoteDraft = { title: "Website scope", projectId, currency: "USD", validUntil: "2026-12-01", terms: "50% upfront", items: [{ description: "Design", quantity: "1.50", unitPrice: "1.25" }, { description: "Build", quantity: "2", unitPrice: "0.10" }] };
assert.equal(quoteLineTotal(draft.items[0]), "1.88");
assert.equal(quoteTotal(draft.items), "2.08");
assert.equal(quoteTotal([{ description: "Exact", quantity: "1", unitPrice: "9999999999.99" }]), "9999999999.99");
assert.equal(quoteTotal([{ description: "Overflow", quantity: "2", unitPrice: "9999999999.99" }]), null);
assert.equal(quoteTotal([{ description: "Invalid", quantity: "0", unitPrice: "10" }]), null);
assert.equal(quoteTotal([{ description: "Invalid", quantity: "1", unitPrice: "-10" }]), null);
assert.equal(quoteTotal([{ description: "Invalid", quantity: "1.001", unitPrice: "10" }]), null);
assert.equal(quoteTotal([]), null);
assert.ok(validateQuoteDraft({ ...draft, projectId: getClientProjects(DEFAULT_CLIENTS[1])[0].id }, DEFAULT_CLIENTS[0]));
assert.ok(validateQuoteDraft({ ...draft, validUntil: "2026-02-30" }, DEFAULT_CLIENTS[0]));
assert.ok(validateQuoteDraft({ ...draft, currency: "XYZ" }, DEFAULT_CLIENTS[0]));

const first = saveQuoteDraft(DEFAULT_CLIENTS, "cl-1", draft, "quote-one", "2026-11-07T12:00:00Z");
assert.equal(getClientQuotes(first[0])[0].totalAmount, "2.08");
assert.equal(first[1], DEFAULT_CLIENTS[1]);
assert.deepEqual(getClientQuotes(first[1]), []);
const edited = saveQuoteDraft(first, "cl-1", { ...draft, title: "Updated title" }, "quote-one", "2026-11-07T13:00:00Z", "quote-one");
assert.equal(getClientQuotes(edited[0]).length, 1);
assert.equal(getClientQuotes(edited[0])[0].revisionNumber, 1);
const prepared = prepareClientQuote(edited, "cl-1", "quote-one", "2026-11-07T14:00:00Z", "2026-11-07");
const frozen = getClientQuotes(prepared[0])[0];
assert.equal(frozen.status, "SENT");
assert.equal(quoteDisplayStatus(frozen, "2026-12-02"), "EXPIRED");
assert.equal(quoteStatistics(latestClientQuotes(getClientQuotes(prepared[0])), "2026-12-02").awaiting, 0);
assert.equal(quoteStatistics(latestClientQuotes(getClientQuotes(prepared[0])), "2026-11-07").awaiting, 1);
const revised = saveQuoteDraft(prepared, "cl-1", { ...draft, title: "Revision two" }, "quote-two", "2026-11-08T12:00:00Z", "quote-one");
assert.equal(getClientQuotes(revised[0]).length, 2);
assert.equal(getClientQuotes(revised[0]).find((quote) => quote.id === "quote-one"), frozen);
assert.equal(latestClientQuotes(getClientQuotes(revised[0]))[0].revisionNumber, 2);
assert.equal(latestClientQuotes(getClientQuotes(revised[0]))[0].status, "DRAFT");
assert.equal(getClientQuotes(saveQuoteDraft(prepared, "cl-1", draft, "quote-one", "now", "quote-one")[0])[0], frozen);
assert.equal(getClientQuotes(saveQuoteDraft(revised, "cl-1", draft, "stale-revision", "now", "quote-one")[0]).length, 2);
assert.equal(getClientQuotes(deleteQuoteDraft(revised, "cl-1", "quote-one")[0]).length, 2, "Frozen quotes cannot be deleted");
assert.equal(latestClientQuotes(getClientQuotes(deleteQuoteDraft(revised, "cl-1", "quote-two")[0]))[0].id, "quote-one");
assert.equal(prepareClientQuote(first, "cl-1", "quote-one", "now", "2027-01-01")[0], first[0], "Expired drafts cannot be prepared");
assert.equal(getClientQuotes(saveQuoteDraft(first, "cl-2", draft, "wrong-client", "now")[1]).length, 0);
assert.equal(prepareClientQuote(first, "cl-2", "quote-one", "now", "2026-11-07")[0], first[0]);
const approved = { ...frozen, status: "APPROVED" as const };
const acceptedClients = [{ ...DEFAULT_CLIENTS[0], quotes: [approved] }, ...DEFAULT_CLIENTS.slice(1)];
const revisedApproved = saveQuoteDraft(acceptedClients, "cl-1", draft, "approved-revision", "2026-11-08T12:00:00Z", approved.id);
assert.equal(getClientQuotes(revisedApproved[0]).find((quote) => quote.id === approved.id), approved);
assert.equal(getClientQuotes(deleteQuoteDraft(acceptedClients, "cl-1", approved.id)[0])[0], approved);

const note: NoteDraft = { title: "Preferences", content: "Use accessible colors", projectId, pinned: false };
assert.ok(validateNoteDraft({ ...note, content: " " }, DEFAULT_CLIENTS[0]));
assert.ok(validateNoteDraft({ ...note, projectId: "other-client-project" }, DEFAULT_CLIENTS[0]));
const noted = saveClientNote(DEFAULT_CLIENTS, "cl-1", note, "note-one", "2026-11-07T12:00:00Z");
assert.equal(noted[1], DEFAULT_CLIENTS[1]);
assert.deepEqual(getClientNotes(noted[1]), []);
const notedTwice = saveClientNote(noted, "cl-1", { ...note, title: "Newer", content: "Follow up" }, "note-two", "2026-11-08T12:00:00Z");
assert.equal(getClientNotes(notedTwice[0])[0].id, "note-two");
const pinned = pinClientNote(notedTwice, "cl-1", "note-one");
assert.equal(getClientNotes(pinned[0])[0].id, "note-one");
assert.equal(getClientNotes(pinned[0], "ACCESSIBLE").length, 1);
assert.equal(getClientNotes(pinned[0], "Landing Page").length, 2);
assert.equal(getClientNotes(pinned[0], "missing").length, 0);
const editedNote = saveClientNote(pinned, "cl-1", { ...note, content: "Revised" }, "note-one", "2026-11-09T12:00:00Z");
assert.equal(getClientNotes(editedNote[0]).find((item) => item.id === "note-one")?.createdAt, "2026-11-07T12:00:00Z");
assert.equal(getClientNotes(deleteClientNote(pinned, "cl-2", "note-one")[0]).length, 2);
assert.equal(getClientNotes(deleteClientNote(pinned, "cl-1", "note-one")[0]).length, 1);
console.log("PASS: quote precision, validation, revisions, frozen/approved quote protection, expiry, note CRUD/search/pinning, and client/project isolation.");
